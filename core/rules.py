def library_size() -> int:
    return len(LIBRARY_RULES)


def _ascii_token_in_text(token: str, text: str) -> bool:
    return re.search(rf"(?<![a-z0-9]){re.escape(token)}(?![a-z0-9])", text) is not None


def _token_in_text(token: str, text: str) -> bool:
    needle = token.strip().lower()
    if len(needle) < 2:
        return False
    if re.search(r"[\u4e00-\u9fff]", needle):
        return needle in text
    return _ascii_token_in_text(needle, text)


def _token_score(token: str) -> int:
    needle = token.strip().lower()
    if needle in _GENERIC_TOKENS:
        return 1
    if re.search(r"[\u4e00-\u9fff]", needle):
        return 10 + len(needle)
    return len(needle)


def match_intent_rules(text: str, *, limit: int = 8) -> list[FofaRule]:
    """Find library rules mentioned in a natural-language intent."""
    haystack = text.strip().lower()
    if not haystack:
        return []
    scored: list[tuple[int, FofaRule]] = []
    for rule in LIBRARY_RULES:
        best = 0
        for token in (rule.name, *rule.aliases):
            if _token_in_text(token, haystack):
                best = max(best, _token_score(token))
        if best:
            scored.append((best, rule))
    scored.sort(key=lambda item: (-item[0], item[1].name))
    strong = [rule for score, rule in scored if score >= 6]
    if strong:
        return strong[:limit]
    matched_categories = [
        category
        for category, patterns in _CATEGORY_PATTERNS.items()
        if any(re.search(pattern, haystack, re.IGNORECASE) for pattern in patterns)
    ]
    if matched_categories:
        return [
            rule
            for rule in LIBRARY_RULES
            if rule.category in {expanded for category in matched_categories for expanded in CATEGORY_ALIASES.get(category, (category,))}
        ][:limit]
    return [rule for _, rule in scored[:limit]]


def rules_hint_for_prompt(intent: str, *, limit: int = 8) -> str:
    matched = match_intent_rules(intent, limit=limit)
    if not matched:
        return ""
    lines = ["Bundled FOFA library matches (use these query strings verbatim as precision strategies; do not invent app= names):"]
    for rule in matched:
        status = "official catalog verified" if rule.verified else "legacy mapping; current name not reverified"
        lines.append(f"- {rule.name} [{rule.category}; {status}]: {rule.query}")
    return "\n".join(lines)


def search_rules(keyword: str = "", *, limit: int | None = None) -> list[FofaRule]:
    needle = keyword.strip().lower()
    if not needle:
        rules = list(LIBRARY_RULES)
        return rules if limit is None else rules[:limit]
    ranked: list[tuple[int, FofaRule]] = []
    for rule in LIBRARY_RULES:
        category_aliases = [alias for alias, targets in CATEGORY_ALIASES.items() if rule.category in targets]
        haystack = " ".join((rule.name, rule.query, rule.category, rule.official_name, *rule.aliases, *category_aliases)).lower()
        if needle not in haystack:
            continue
        score = 0
        if needle == rule.name.lower() or needle in {item.lower() for item in rule.aliases}:
            score = 0
        elif needle in rule.name.lower():
            score = 1
        else:
            score = 2
        ranked.append((score, rule))
    ranked.sort(key=lambda item: (item[0], item[1].name))
    matches = [rule for _, rule in ranked]
    return matches if limit is None else matches[:limit]


def resolve_rule_query(keyword: str) -> FofaRule:
    matches = search_rules(keyword, limit=20)
    exact = [rule for rule in matches if keyword.strip().lower() in {rule.name.lower(), *(item.lower() for item in rule.aliases)}]
    chosen = exact[0] if len(exact) == 1 else (matches[0] if len(matches) == 1 else None)
    if chosen is None:
        names = "、".join(rule.name for rule in matches[:8]) or "无匹配"
        raise ValueError(f"规则库无法唯一匹配 {keyword!r}。候选：{names}。请用 `fofamap rules -k {keyword}` 查看。")
    return chosen


def rules_catalog(keyword: str = "", *, category: str = "", limit: int | None = None) -> dict[str, Any]:
    if limit is not None and not 1 <= limit <= 200:
        raise ValueError("Rule limit must be between 1 and 200")
    rules = search_rules(keyword)
    if category:
        names = {name.casefold(): name for name in OFFICIAL_CATEGORY_IDS}
        targets = CATEGORY_ALIASES.get(category, (names.get(category.casefold(), category),))
        if not any(name in OFFICIAL_CATEGORY_IDS for name in targets):
            raise ValueError("Unknown rule category; inspect category_summary first")
        rules = [rule for rule in rules if rule.category in targets]
    matched_count = len(rules)
    if limit is not None:
        rules = sorted(rules, key=lambda rule: not rule.verified)[:limit]
    grouped: dict[str, list[dict[str, Any]]] = {}
    payload = []
    for rule in rules:
        item = {
            "name": rule.name,
            "query": rule.query,
            "category": rule.category,
            "aliases": ", ".join(rule.aliases),
            "verified": rule.verified,
            "official_name": rule.official_name or None,
            "official_category_id": rule.official_category_id,
            "verified_at": LIBRARY_CHECKED_AT if rule.verified else None,
        }
        grouped.setdefault(rule.category, []).append(item)
        payload.append(item)
    return {
        "source": "https://fofa.info/library",
        "note": "已核验项保留官网原始 app= 表达式；legacy 项为旧版兼容映射，本轮未能核实，不代表最新官方名称。",
        "checked_at": LIBRARY_CHECKED_AT,
        "official_category_count": len(OFFICIAL_CATEGORY_IDS),
        "verified_count": sum(rule.verified for rule in LIBRARY_RULES),
        "legacy_count": sum(not rule.verified for rule in LIBRARY_RULES),
        "category_summary": [
            {"name": name, "count": sum(rule.category == name for rule in LIBRARY_RULES),
             "verified": sum(rule.category == name and rule.verified for rule in LIBRARY_RULES)}
            for name in sorted(OFFICIAL_CATEGORY_IDS)
        ],
        "total": len(LIBRARY_RULES),
        "matched_count": matched_count,
        "has_more": matched_count > len(rules),
        "count": len(rules),
        "categories": grouped,
        "rules": payload,
    }
